BASE_CONFIG = b"""\
python:
  - 3.13.* *_cp313
libboost_devel:
  - '1.88'
keep:
  - base
"""

BOOST_MIGRATION = b"""\
__migrator:
  build_number: 1
libboost_devel:
  - '1.90'
migrator_ts: 1234
"""


def _conda_package(files):
    tar_payload = io.BytesIO()
    with tarfile.open(fileobj=tar_payload, mode="w") as archive:
        for name, content in files.items():
            info = tarfile.TarInfo(name)
            info.size = len(content)
            archive.addfile(info, io.BytesIO(content))
    compressed = zstandard.ZstdCompressor().compress(tar_payload.getvalue())
    conda_payload = io.BytesIO()
    with zipfile.ZipFile(conda_payload, mode="w") as archive:
        archive.writestr("metadata.json", '{"conda_pkg_format_version": 2}')
        archive.writestr("pkg-test.tar.zst", compressed)
        archive.writestr("info-test.tar.zst", b"")
    return conda_payload.getvalue()


def test_read_pinning_conda_package():
    payload = _conda_package(
        {
            "conda_build_config.yaml": BASE_CONFIG,
            "share/conda-forge/migrations/libboost190.yaml": BOOST_MIGRATION,
            "ignored.txt": b"not part of the pinning inputs",
        }
    )

    base, migrations = _read_pinning_package(payload)

    assert base == BASE_CONFIG
    assert migrations == {"libboost190": BOOST_MIGRATION}


def test_render_applies_base_migration_then_override(tmp_path):
    config_path = tmp_path / "rock_the_conda_pinning.yaml"
    config_path.write_text(
        """\
conda_forge_pinning_version: 2026.01.02.03.04.05
migrations:
  - libboost190
pinning_overrides:
  python:
    - 3.14.* *_cp314
"""
    )
    output_path = tmp_path / "conda_build_config.yaml"

    rendered = render_pinning(
        config_path,
        output_path,
        package=(BASE_CONFIG, {"libboost190": BOOST_MIGRATION}),
    )

    assert rendered["python"] == ["3.14.* *_cp314"]
    assert rendered["libboost_devel"] == ["1.90"]
    assert rendered["keep"] == ["base"]
    assert "__migrator" not in rendered
    assert "migrator_ts" not in rendered
    assert output_path.read_text().startswith(
        "# Generated by rock-the-conda-pinning-render from rock_the_conda_pinning.yaml."
    )
    assert not any(line.endswith(" ") for line in output_path.read_text().splitlines())


