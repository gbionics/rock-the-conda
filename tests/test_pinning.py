def test_existing_active_migration_is_kept_and_overrides_are_unchanged(tmp_path):
    config_path = tmp_path / "rock_the_conda_pinning.yaml"
    config_path.write_text(
        """\
conda_forge_pinning_version: old
migrations:
  - boost
pinning_overrides:
  # This comment and value are maintained locally.
  python:
    - 3.14.* *_cp314
"""
    )
    package = (BASE_CONFIG, {"boost": BOOST_MIGRATION})
    pending_status = {"done": [], "in-pr": ["pcl"]}

    with (
        patch("rock_the_conda.pinning.download_pinning_package", return_value=package),
        patch("rock_the_conda.pinning.get_migration_status", return_value=pending_status),
        patch("rock_the_conda.pinning.package_feedstocks", side_effect=lambda name: {name}),
    ):
        version, migrations, _ = update_pinning(
            config_path,
            base_dir=tmp_path,
            dependencies={"pcl"},
            latest_distribution=("new", "https://example.invalid/package.conda"),
        )

    assert version == "new"
    assert migrations == ["boost"]
    text = config_path.read_text()
    assert "This comment and value are maintained locally." in text
    parsed = ruamel.yaml.YAML(typ="safe").load(text)
    assert parsed["pinning_overrides"] == {"python": ["3.14.* *_cp314"]}


@pytest.mark.parametrize("null_value", ["null", "", "~"])
def test_update_preserves_explicit_null_overrides(tmp_path, null_value):
    config_path = tmp_path / "rock_the_conda_pinning.yaml"
    config_path.write_text(
        f"""\
conda_forge_pinning_version: old
migrations: []
pinning_overrides:
  # Built locally; remove the inherited pin.
  pytorch: {null_value}  # Keep this deletion.
  libtorch: {null_value}
  python:
    - 3.14.* *_cp314
"""
    )
    with patch("rock_the_conda.pinning.download_pinning_package", return_value=(BASE_CONFIG, {})):
        for _ in range(2):
            update_pinning(
                config_path,
                dependencies=set(),
                latest_distribution=("new", "https://example.invalid/package.conda"),
            )

    text = config_path.read_text()
    assert re.search(r"pytorch: null\s+# Keep this deletion\.", text)
    assert "libtorch: null" in text
    assert "Built locally; remove the inherited pin." in text
    assert ruamel.yaml.YAML(typ="safe").load(text)["pinning_overrides"] == {
        "pytorch": None,
        "libtorch": None,
        "python": ["3.14.* *_cp314"],
    }
    # Updating a spec must not change the renderer's null-item formatting.
    output_path = tmp_path / "rendered.yaml"
    render_pinning(
        config_path,
        output_path,
        package=(b"pytorch: [old]\nlibtorch: [old]\ntarget_goexe:\n  -  # [unix]\n", {}),
    )
    output = output_path.read_text()
    assert "pytorch:" not in output and "libtorch:" not in output
    assert re.search(r"^  -\s+# \[unix]$", output, re.MULTILINE)


def test_explicit_zip_groups_allow_independent_stdlib_override(tmp_path):
    config_path = tmp_path / "pinning.yaml"
    config_path.write_text("""\
conda_forge_pinning_version: example
pinning_overrides:
  c_stdlib_version: [2.28]
  zip_keys:
    - [c_compiler_version, cxx_compiler_version]
""")
    base = b"""\
c_compiler_version: [14, 15]
cxx_compiler_version: [14, 15]
c_stdlib_version: [2.17, 2.28]
zip_keys:
  - [c_compiler_version, cxx_compiler_version, c_stdlib_version]
"""
    rendered = render_pinning(config_path, tmp_path / "rendered.yaml", package=(base, {}))
    assert rendered["c_stdlib_version"] == [2.28]
    assert rendered["c_compiler_version"] == [14, 15]
    assert rendered["cxx_compiler_version"] == [14, 15]
    assert rendered["zip_keys"] == [["c_compiler_version", "cxx_compiler_version"]]
