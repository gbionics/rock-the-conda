def test_cfep9_scoped_migration_only_replaces_matching_platform_values():
    yaml = ruamel.yaml.YAML()
    base = yaml.load(
        """\
c_stdlib_version:
  - 2.17  # [linux]
  - 2.28  # [linux and (x86_64 or aarch64)]
  - 11.0  # [osx]
"""
    )
    migration = yaml.load(
        """\
c_stdlib_version:  # [osx]
  - 12.0           # [osx]
"""
    )

    merged = variant_add(base, migration)

    assert merged["c_stdlib_version"] == [2.17, 2.28, 12.0]
    output = io.StringIO()
    yaml.dump(merged, output)
    assert "2.17" in output.getvalue() and "# [linux]" in output.getvalue()
    assert "2.28" in output.getvalue()
    assert "12.0" in output.getvalue() and "# [osx]" in output.getvalue()


