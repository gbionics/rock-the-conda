def test_cfep9_key_add_updates_zip_group():
    base = {
        "python": ["3.12.*", "3.13.*"],
        "is_python_min": [True, False],
        "zip_keys": [["python", "is_python_min"]],
    }
    migration = {
        "__migrator": {
            "operation": "key_add",
            "primary_key": "python",
            "ordering": {"python": ["3.12.*", "3.13.*", "3.14.*"]},
        },
        "python": ["3.14.*"],
        "is_python_min": [False],
    }

    merged = variant_add(base, migration)

    assert merged["python"] == ["3.12.*", "3.13.*", "3.14.*"]
    assert merged["is_python_min"] == [True, False, False]


def test_cfep9_merges_pin_run_as_build_and_zip_keys():
    merged = variant_add(
        {
            "pin_run_as_build": {"old": {"max_pin": "x"}},
            "zip_keys": [["python", "numpy"]],
        },
        {
            "pin_run_as_build": {"new": {"max_pin": "x.x"}},
            "zip_keys": [["python", "numpy", "is_python_min"]],
        },
    )

    assert merged["pin_run_as_build"] == {
        "old": {"max_pin": "x"},
        "new": {"max_pin": "x.x"},
    }
    assert merged["zip_keys"] == [["is_python_min", "numpy", "python"]]


def test_cfep9_duplicate_primary_values_keep_zip_key_columns_aligned():
    merged = variant_add(
        {
            "python": ["3.13"],
            "numpy": ["1.0"],
            "zip_keys": [["python", "numpy"]],
        },
        {
            "__migrator": {"primary_key": "python"},
            "python": ["3.13"],
            "numpy": ["2.0"],
        },
    )

    assert len(merged["python"]) == len(merged["numpy"])


